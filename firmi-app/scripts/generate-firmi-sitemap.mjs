import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const origin='https://firmi.predictorian.workers.dev';
const config=JSON.parse(fs.readFileSync(path.join(root,'seo-public-pages.json'),'utf8'));
if(!Array.isArray(config.paths)||!config.paths.includes('/'))throw Error('SEO config requires paths including /.');
const app=fs.existsSync(path.join(root,'app'))?'app':'src/app';
const escape=x=>x.replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;').replaceAll('"','&quot;').replaceAll("'",'&apos;');
const paths=[...new Set(config.paths)];
for(const p of paths){
 if(typeof p!=='string'||!/^\/(?:[a-z0-9_-]+(?:\/[a-z0-9_-]+)*)?$/.test(p)||/^\/(?:api|app|auth|billing|_next)(?:\/|$)/.test(p))throw Error('Invalid or private SEO path: '+p);
 const page=path.join(root,app,p.slice(1),'page.tsx');
 if(!fs.existsSync(page))throw Error('Public page not found: '+page);
}
const sitemap='<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'+paths.sort().map(p=>'  <url><loc>'+escape(origin+p)+'</loc></url>').join('\n')+'\n</urlset>\n';
const robots='User-agent: *\nAllow: /\nDisallow: /api/\nDisallow: /app$\nDisallow: /app/\nDisallow: /auth\nDisallow: /billing\n\nSitemap: '+origin+'/sitemap.xml\n';
fs.mkdirSync(path.join(root,'lib'),{recursive:true});
fs.writeFileSync(path.join(root,'lib/firmi-seo-manifest.ts'),'// Generated by scripts/generate-firmi-sitemap.mjs.\nexport const PUBLIC_PATHS: readonly string[] = '+JSON.stringify(paths)+';\nexport const SITEMAP_XML = '+JSON.stringify(sitemap)+';\nexport const ROBOTS_TXT = '+JSON.stringify(robots)+';\n');
console.log('Sitemap: '+paths.length+' public page(s), '+origin+'/sitemap.xml');
